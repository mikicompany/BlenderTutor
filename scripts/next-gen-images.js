// Generates WebP and AVIF copies of every raster image in public/blog-images,
// and writes src/blog/image-formats.js mapping each original to the next-gen
// formats that exist for it. The blog's markdown <img> renderer reads that map
// and emits a <picture> with <source> elements, so modern browsers download the
// much smaller AVIF/WebP (often 70–80% smaller than the JPEG) while anything
// older still gets the original. The hero image is each post's LCP, so this is
// a direct Core Web Vitals + bandwidth win across every post.
//
// Encoders: WebP via ImageMagick `convert`, AVIF via `avifenc`. Either may be
// absent in a given environment — the step skips the missing format and records
// only what it actually produced, so the build never fails for lack of a codec.
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { join } from 'node:path'

const DIR = 'public/blog-images'
const OUT = 'src/blog/image-formats.js'
const SOURCE_EXT = new Set(['jpg', 'jpeg', 'png'])

function have(cmd) {
  try { execFileSync('bash', ['-lc', `command -v ${cmd}`], { stdio: 'ignore' }); return true }
  catch { return false }
}

const hasConvert = have('convert')
const hasAvifenc = have('avifenc')

function fresh(out, src) {
  return existsSync(out) && statSync(out).mtimeMs >= statSync(src).mtimeMs
}

const formats = {}
let madeWebp = 0, madeAvif = 0, skipped = 0

for (const file of readdirSync(DIR).sort()) {
  const ext = file.slice(file.lastIndexOf('.') + 1).toLowerCase()
  if (!SOURCE_EXT.has(ext)) continue
  const src = join(DIR, file)
  const base = file.slice(0, file.lastIndexOf('.'))
  const avail = []

  if (hasConvert) {
    const webp = join(DIR, `${base}.webp`)
    if (!fresh(webp, src)) {
      execFileSync('convert', [src, '-quality', '82', '-define', 'webp:method=6', webp])
      madeWebp++
    } else skipped++
    avail.push('webp')
  }

  if (hasAvifenc) {
    const avif = join(DIR, `${base}.avif`)
    if (!fresh(avif, src)) {
      // --min/--max are AV1 quantizers (lower = higher quality); -s 6 trades a
      // little size for a much faster encode than the default.
      execFileSync('avifenc', ['--min', '20', '--max', '35', '-s', '6', '-j', 'all', src, avif], { stdio: 'ignore' })
      madeAvif++
    }
    avail.push('avif')
  }

  if (avail.length) formats[`/blog-images/${file}`] = avail
}

const body =
  '// AUTO-GENERATED by scripts/next-gen-images.js — do not edit by hand.\n' +
  '// Maps each /blog-images original to the next-gen formats generated for it,\n' +
  '// so the blog <img> renderer can offer <picture> <source>s (AVIF/WebP).\n' +
  `export const IMG_FORMATS = ${JSON.stringify(formats, null, 0)}\n`
writeFileSync(OUT, body)

const codecs = [hasConvert && 'webp', hasAvifenc && 'avif'].filter(Boolean).join('+') || 'none'
console.log(`next-gen-images — ${Object.keys(formats).length} images [${codecs}] (made ${madeWebp} webp, ${madeAvif} avif, ${skipped} up-to-date)`)
