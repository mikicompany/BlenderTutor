// Generates src/blog/image-dims.js: a map of /blog-images/<file> -> [width, height].
//
// The blog's in-content images render through react-markdown as bare <img>, with
// no intrinsic size, so the browser reserves no space and the text below jumps as
// each image loads (cumulative layout shift). Giving every <img> explicit
// width/height lets the browser reserve the right box up front. Dimensions are
// read here at build time with a tiny dependency-free parser (JPEG + PNG + SVG
// viewBox), so nothing needs ImageMagick or an npm image library at build.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const DIR = 'public/blog-images'
const OUT = 'src/blog/image-dims.js'

function jpegSize(buf) {
  if (buf[0] !== 0xff || buf[1] !== 0xd8) return null
  let i = 2
  while (i < buf.length) {
    if (buf[i] !== 0xff) { i++; continue }
    const m = buf[i + 1]
    i += 2
    // Standalone markers carry no length segment.
    if (m === 0xd8 || m === 0xd9 || (m >= 0xd0 && m <= 0xd7) || m === 0x01) continue
    if (i + 1 >= buf.length) break
    const segLen = buf.readUInt16BE(i)
    const isSOF = m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc
    if (isSOF) {
      const height = buf.readUInt16BE(i + 3)
      const width = buf.readUInt16BE(i + 5)
      return [width, height]
    }
    i += segLen
  }
  return null
}

function pngSize(buf) {
  if (buf.readUInt32BE(0) !== 0x89504e47) return null
  return [buf.readUInt32BE(16), buf.readUInt32BE(20)]
}

function svgSize(buf) {
  const s = buf.toString('utf8', 0, 2000)
  const vb = s.match(/viewBox\s*=\s*["']\s*[\d.]+\s+[\d.]+\s+([\d.]+)\s+([\d.]+)/i)
  if (vb) return [Math.round(+vb[1]), Math.round(+vb[2])]
  const w = s.match(/\bwidth\s*=\s*["']([\d.]+)/i)
  const h = s.match(/\bheight\s*=\s*["']([\d.]+)/i)
  if (w && h) return [Math.round(+w[1]), Math.round(+h[1])]
  return null
}

const dims = {}
for (const file of readdirSync(DIR).sort()) {
  const ext = file.slice(file.lastIndexOf('.') + 1).toLowerCase()
  const buf = readFileSync(join(DIR, file))
  let size = null
  if (ext === 'jpg' || ext === 'jpeg') size = jpegSize(buf)
  else if (ext === 'png') size = pngSize(buf)
  else if (ext === 'svg') size = svgSize(buf)
  if (size && size[0] > 0 && size[1] > 0) dims[`/blog-images/${file}`] = size
}

const body =
  '// AUTO-GENERATED by scripts/image-dims.js — do not edit by hand.\n' +
  '// Maps /blog-images/<file> to [width, height] so blog <img>s can reserve\n' +
  '// space and avoid layout shift.\n' +
  `export const IMAGE_DIMS = ${JSON.stringify(dims, null, 0)}\n`
writeFileSync(OUT, body)
console.log(`image-dims — ${Object.keys(dims).length} images`)
